/**
 * One-shot importer: pulls the 200-question BANK out of the practice mockup in
 * internal/ and writes it into src/lib/bank as one module per site topic slug.
 *
 * The mockup's 20 buckets are collapsed onto the site's own taxonomy — the two
 * "safe and effective care" buckets merge, the rest map one to one. Re-run it
 * with `node scripts/import-question-bank.mjs` if the mockup is ever refreshed.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const SRC = join(ROOT, "internal", "nursia_practice.html");
const OUT = join(ROOT, "src", "lib", "bank");

/** mockup bucket -> site topic slug. Two buckets land on safe-care by design. */
const MAP = {
  "management-of-care": "safe-care",
  "safety-infection-control": "safe-care",
  "health-promotion": "health-promotion",
  psychosocial: "psychosocial",
  "basic-care-comfort": "basic-care",
  "pharm-parenteral": "pharmacology",
  "reduction-risk": "risk-reduction",
  "physiological-adaptation": "med-surg",
  cardiovascular: "cardiovascular",
  respiratory: "respiratory",
  endocrine: "endocrine",
  neuro: "neurological",
  gastrointestinal: "gastrointestinal",
  "renal-genitourinary": "renal-genitourinary",
  maternity: "maternity-newborn",
  pediatrics: "pediatrics",
  "mental-health": "mental-health",
  fundamentals: "fundamentals",
  "prioritization-delegation": "prioritization-delegation",
  "dosage-lab-values": "dosage-and-labs",
};

/** short, stable id prefix per slug — ids show in the question card meta rail */
const PREFIX = {
  "safe-care": "SE",
  "health-promotion": "HP",
  psychosocial: "PS",
  "basic-care": "BC",
  pharmacology: "PH",
  "risk-reduction": "RR",
  "med-surg": "MS",
  cardiovascular: "CV",
  respiratory: "RE",
  endocrine: "EN",
  neurological: "NE",
  gastrointestinal: "GI",
  "renal-genitourinary": "RG",
  "maternity-newborn": "MN",
  pediatrics: "PD",
  "mental-health": "MH",
  fundamentals: "FN",
  "prioritization-delegation": "PR",
  "dosage-and-labs": "DL",
};

const html = readFileSync(SRC, "utf8");
const start = html.indexOf("const BANK = ");
if (start < 0) throw new Error("BANK literal not found in " + SRC);
const line = html.slice(start + "const BANK = ".length, html.indexOf("\n", start));
const bank = JSON.parse(line.replace(/;\s*$/, ""));

/* The mockup prefixes the winning option's explanation with "Correct." — the
   UI marks that option itself, so the word is redundant in our rendering. */
const trim = (s) => String(s).replace(/^correct[.:,]?\s*/i, "").trim();

const grouped = new Map();
for (const [bucket, questions] of Object.entries(bank)) {
  const slug = MAP[bucket];
  if (!slug) throw new Error("unmapped bucket: " + bucket);
  const list = grouped.get(slug) ?? [];
  for (const q of questions) {
    list.push({
      id: `${PREFIX[slug]}-${String(list.length + 1).padStart(3, "0")}`,
      stem: q.q,
      options: q.opts,
      answer: q.a,
      rationale: q.r,
      why: (q.why ?? []).map(trim),
    });
  }
  grouped.set(slug, list);
}

/* Clear only what this script generated — types.ts is hand-written. */
mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) {
  if (f !== "types.ts") rmSync(join(OUT, f));
}

const banner = `/* Generated by scripts/import-question-bank.mjs — do not edit by hand. */\n`;

for (const [slug, list] of grouped) {
  writeFileSync(
    join(OUT, `${slug}.ts`),
    `${banner}import type { BankQuestion } from "./types";\n\n` +
      `const questions: BankQuestion[] = ${JSON.stringify(list, null, 2)};\n\nexport default questions;\n`,
    "utf8",
  );
}

const slugs = [...grouped.keys()].sort();
writeFileSync(
  join(OUT, "counts.ts"),
  `${banner}\n/** How many questions each topic actually has in the bank. */\n` +
    `export const BANK_COUNTS: Record<string, number> = ${JSON.stringify(
      Object.fromEntries(slugs.map((s) => [s, grouped.get(s).length])),
      null,
      2,
    )};\n`,
  "utf8",
);

writeFileSync(
  join(OUT, "loaders.ts"),
  `${banner}import type { BankQuestion } from "./types";\n\n` +
    `/* One dynamic import per topic so a visitor downloads the set they clicked\n` +
    `   and not the other nineteen. */\n` +
    `export const BANK_LOADERS: Record<string, () => Promise<BankQuestion[]>> = {\n` +
    slugs
      .map((s) => `  ${JSON.stringify(s)}: () => import("./${s}").then((m) => m.default),`)
      .join("\n") +
    `\n};\n`,
  "utf8",
);

console.log(
  `wrote ${slugs.length} topic modules, ${[...grouped.values()].reduce((n, l) => n + l.length, 0)} questions`,
);
